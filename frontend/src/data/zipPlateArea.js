/** Search across zip/plate/area datasets. */
export function search(type, query) {
  const q = (query || '').trim().toLowerCase()
  if (!q) return []

  let dataset
  switch (type) {
    case 'zip':
      dataset = zipData
      break
    case 'plate':
      dataset = plateData
      break
    case 'area':
      dataset = areaData
      break
    default:
      return []
  }

  return dataset.filter(item => {
    const key = type === 'zip' ? item.code : type === 'plate' ? item.prefix : item.code
    const text = `${key} ${item.province} ${item.city} ${item.district || ''} ${item.note || ''}`.toLowerCase()
    return text.includes(q)
  })
}
